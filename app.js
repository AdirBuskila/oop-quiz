/* ---------- session ---------- */
function startSession(){
  if(!QS.length) return;
  S._views=null;
  const opts=selectedOpts();
  const pickedExam = selectedExam();
  let pool;
  if(pickedExam){
    // full-exam mode replays EVERY question of that paper, duplicates included
    pool = examQuestions(pickedExam).slice().sort((a,b)=>qNum(a)-qNum(b));
  } else {
    pool = shuffle(filteredPool(S.topic, opts));
  }
  if(!pool.length) return;
  if(S.mode==="exam"){
    if(pickedExam){ S.exam.count = pool.length; }
    else { S.exam.count = Math.min(parseInt($("#examCount").value,10), pool.length); pool = pool.slice(0, S.exam.count); }
    S.exam.minutes = parseInt($("#examMinutes").value,10);
    S.exam.answers = {};
    S.exam.endAt = Date.now() + S.exam.minutes*60000;
    startTimer();
  }
  S.pool = pool; S.pos = 0; S.hist = []; S.hpos = 0;
  $("#prevBtn").classList.remove("hidden");
  show("screen-quiz");
  renderQuestion();
}

function makeView(q){
  // shuffle by stable option id; skipped when an option cites its siblings by printed
  // letter ("תשובות א ו-ב נכונות") — shuffling would make that reference nonsense.
  const ids = (q.options||[]).map(o=>o.id);
  const order = q.lockOrder ? ids : shuffle(ids);
  const correctSet = new Set(order.map((id,i)=>isAccepted(q,id)?i:-1).filter(i=>i>=0));
  return { q, order, correctDisplay: order.indexOf(q.correctId), correctSet, answered:false, chosen:null };
}

function renderQuestion(){
  let q = S.pool[S.pos];
  if(S.mode==="exam"){
    S._views = S._views || {};
    S.current = S._views[q.id] || makeView(q);   // stable shuffle on back-navigation
    S._views[q.id] = S.current;
  } else {
    // practice: every shown question is kept in S.hist (with its shuffle), so "back" replays it as answered
    if(!S.hist[S.hpos]) S.hist[S.hpos] = Object.assign(makeView(q), {pos:S.pos});
    S.current = S.hist[S.hpos]; q = S.current.q;
  }
  const v=S.current;

  $("#qTopic").innerHTML = labelHtml(topicLabelOf(q));
  $("#qSource").textContent = examLabelOf(q) + (Number.isInteger(q.num) ? ` · שאלה ${q.num}` : "");
  const badge=$("#qBadge");
  badge.textContent = q.official ? "מפתרון רשמי" : "תשובה לא רשמית";
  badge.className = "chip " + (q.official?"official":"unofficial");
  $("#qConf").classList.toggle("hidden", q.confidence!=="low");

  $("#qContext").innerHTML = q.contextId ? contextHtml(CTX[q.contextId]) : "";
  $("#questionText").innerHTML = questionHtml(q);
  $("#questionText").dataset.qid = q.id;   // read by tools/verify_dom.js / shoot.js
  $("#qExtras").innerHTML = extrasHtml(q);

  $("#optionsList").innerHTML = v.order.map((oid,disp)=>
    `<button class="opt" data-disp="${disp}" data-oid="${escapeHtml(oid)}">
       <span class="key">${HE_KEYS[disp]||disp+1}</span>
       <span class="txt">${optionHtml(optById(q,oid))}</span>
     </button>`).join("");
  document.querySelectorAll("#optionsList .opt").forEach(b=> b.onclick=()=>choose(parseInt(b.dataset.disp,10)));

  const fb=$("#feedback"); fb.className="feedback hidden"; fb.innerHTML="";

  if(S.mode==="exam" && q.id in S.exam.answers){
    markExamChoice(v.order.indexOf(S.exam.answers[q.id]));
  }

  const pos = S.mode==="exam" ? S.pos : v.pos;   // in practice the shown question may sit behind the pool cursor
  $("#progressFill").style.width = ((pos)/(S.pool.length))*100 + "%";
  if(S.mode==="exam"){
    $("#quizMeta").innerHTML = `שאלה ${S.pos+1}/${S.pool.length} <span id="tmr" class="timer"></span>`;
    renderTimer();
    $("#nextBtn").classList.toggle("hidden", S.pos>=S.pool.length-1);
    $("#submitExamBtn").classList.toggle("hidden", S.pos<S.pool.length-1);
    $("#prevBtn").disabled = S.pos===0;
    $("#streakBox").textContent = `נענו ${Object.keys(S.exam.answers).length}/${S.pool.length}`;
  } else {
    $("#quizMeta").textContent = `שאלה ${pos+1} מתוך ${S.pool.length}`;
    $("#prevBtn").disabled = S.hpos===0;
    $("#nextBtn").classList.toggle("hidden", !v.answered);   // appears after answering
    $("#submitExamBtn").classList.add("hidden");
    if(v.answered) paintAnswered(v);                        // navigated back to an answered question
    const a=P.stats.answered,c=P.stats.correct;
    $("#streakBox").textContent = `רצף נכון: ${S.streak||0} · דיוק כולל ${a?Math.round(c/a*100):0}%`;
  }
}

/* ---------- answering ---------- */
function choose(disp){
  const v=S.current, q=v.q;
  if(S.mode==="exam"){
    S.exam.answers[q.id] = v.order[disp];   // store the chosen option ID, never the position
    markExamChoice(disp);
    $("#streakBox").textContent = `נענו ${Object.keys(S.exam.answers).length}/${S.pool.length}`;
    return;
  }
  if(v.answered) return;
  v.answered=true; v.chosen=disp; v.correct = isAccepted(q, v.order[disp]);
  paintAnswered(v);
  recordAnswer(q, v.correct);
  S.streak = v.correct ? (S.streak||0)+1 : 0;
  $("#nextBtn").focus();
  renderTopStats();
  const a=P.stats.answered,c=P.stats.correct;
  $("#streakBox").textContent = `רצף נכון: ${S.streak} · דיוק כולל ${a?Math.round(c/a*100):0}%`;
}
/* Paint an answered practice question: lock the options, mark right/wrong, show the feedback.
   Runs when answering and again when navigating back to an already-answered question. */
function paintAnswered(v){
  const q=v.q, correct=v.correct;
  document.querySelectorAll("#optionsList .opt").forEach((b,i)=>{
    b.disabled=true;
    if(v.correctSet.has(i)) b.classList.add("correct");
    else if(i===v.chosen) b.classList.add("wrong");
  });
  // Explanations cite the ORIGINAL exam letters ("הפרכת א…"), but options were shuffled —
  // once answered, tag every option with its letter in the source exam.
  const shuffled = v.order.some((oid,i)=> q.options[i] && q.options[i].id!==oid);
  if(shuffled){
    document.querySelectorAll("#optionsList .opt").forEach((b,i)=>{
      const src = q.options.findIndex(o=>o.id===v.order[i]);
      b.insertAdjacentHTML("beforeend", `<span class="orig-key" title="האות במבחן המקורי">במקור: ${HE_KEYS[src]||src+1}</span>`);
    });
  }
  const fb=$("#feedback");
  fb.className = "feedback " + (correct?"good":"bad");
  const srcNote = SRC_NOTE[q.answerSource] || "";
  const multi = acceptedIdsOf(q).length>1;
  fb.innerHTML = `<div class="verdict">${correct?"✓ נכון":"✗ לא נכון"}</div>`+
    (shuffled && q.explanationHtml ? `<span class="note">האותיות בהסבר מתייחסות לסדר המקורי במבחן (מסומן "במקור" ליד כל תשובה).</span>` : "")+
    (q.explanationHtml ? `<div class="expl">${q.explanationHtml}</div>` : `<div class="expl expl-none">אין הסבר במקור.</div>`)+
    (multi?`<span class="accept-note">בשאלה זו התקבלה יותר מתשובה אחת כנכונה.</span>`:"")+
    (q.official?"":`<span class="note">⚠ תשובה לא רשמית — מומלץ לאמת מול המקור.</span>`)+
    (q.confidence==="low"?`<span class="note">⚠ רמת ביטחון נמוכה בתשובה המסומנת.</span>`:"")+
    (srcNote?`<span class="note">${escapeHtml(srcNote)}</span>`:"")+
    `<span class="note">מקור: ${escapeHtml(examLabelOf(q))}${Number.isInteger(q.num)?` · שאלה ${q.num}`:""}</span>`;
  $("#nextBtn").classList.remove("hidden");
}

function markExamChoice(disp){ document.querySelectorAll("#optionsList .opt").forEach((b,i)=> b.classList.toggle("chosen-exam", i===disp)); }
function recordAnswer(q, correct){ P.stats.answered++; if(correct) P.stats.correct++; P.perQ[q.id]={correct, t:Date.now()}; saveProgress(); }

/* ---------- navigation ---------- */
function next(){
  if(S.mode==="practice"){
    if(!S.current || !S.current.answered) return;
    if(S.hpos<S.hist.length-1){ S.hpos++; renderQuestion(); return; }   // forward through history after going back
    if(S.pos>=S.pool.length-1){ S.pool = shuffle(S.pool); S.pos=0; } else S.pos++;
    S.hpos++;
    renderQuestion();
  } else if(S.pos<S.pool.length-1){ S.pos++; renderQuestion(); }
}
function prev(){
  if(S.mode==="exam"){ if(S.pos>0){ S.pos--; renderQuestion(); } }
  else if(S.hpos>0){ S.hpos--; renderQuestion(); }   // practice: back to the previous question, shown as answered
}

/* ---------- timer (exam) ---------- */
function startTimer(){ clearInterval(S.exam.timer); S.exam.timer=setInterval(renderTimer,1000); }
function renderTimer(){
  const el=$("#tmr"); if(!el) return;
  let ms=S.exam.endAt-Date.now();
  if(ms<=0){ ms=0; clearInterval(S.exam.timer); submitExam(true); return; }
  const m=Math.floor(ms/60000), s=Math.floor(ms%60000/1000);
  el.textContent = `⏱ ${m}:${String(s).padStart(2,"0")}`;
  el.classList.toggle("danger", ms<60000);
}

/* ---------- exam grading ---------- */
function submitExam(auto){
  clearInterval(S.exam.timer);
  if(!auto){
    const unans=S.pool.length-Object.keys(S.exam.answers).length;
    if(unans>0 && !confirm(`נותרו ${unans} שאלות ללא מענה. להגיש בכל זאת?`)){ startTimer(); return; }
  }
  let correct=0; const byTopic={}; const review=[];
  S.pool.forEach(q=>{
    const chosen = q.id in S.exam.answers ? S.exam.answers[q.id] : null;  // option id or null
    const ok = isAccepted(q, chosen);
    if(ok) correct++;
    recordAnswer(q, ok);
    (byTopic[q.topic] = byTopic[q.topic] || {n:0,c:0}); byTopic[q.topic].n++; if(ok) byTopic[q.topic].c++;
    review.push({q, chosen, ok});
  });
  renderResults(correct, byTopic, review);
  renderTopStats();
  show("screen-results");
}
function renderResults(correct, byTopic, review){
  const total=S.pool.length, pct=total?Math.round(correct/total*100):0;
  $("#resultsSummary").innerHTML =
    `<div class="scorering" style="--p:${pct}"><span>${pct}%</span></div>`+
    `<div class="txt"><b>${correct} / ${total}</b> תשובות נכונות<br>`+
    `<span style="color:var(--muted)">${pct>=60?"עברת! 🎉":"עוד קצת תרגול 💪"}</span></div>`;
  $("#resultsByTopic").innerHTML = Object.entries(byTopic).map(([t,o])=>{
    const p=Math.round(o.c/o.n*100);
    return `<div class="tline"><span>${labelHtml(TOPIC_LABEL[t]||t)}</span><span class="tbar"><i style="width:${p}%"></i></span><span>${o.c}/${o.n}</span></div>`;
  }).join("");
  $("#resultsReview").innerHTML = review.map(r=>{
    const v=r.q;
    const chosenTxt = r.chosen!=null ? optionHtml(optById(v,r.chosen)) : "— לא נענתה —";
    const acc = acceptedIdsOf(v);
    const correctTxt = acc.map(id=>optionHtml(optById(v,id))).join(`<span class="or">או</span>`);
    return `<div class="rev ${r.ok?"ok":"bad"}">
      <div class="rq">${questionHtml(v)}</div>
      ${v.contextId?contextHtml(CTX[v.contextId]):""}
      ${extrasHtml(v)}
      <div class="ra"><span class="${r.ok?"good":"miss"}">תשובתך: ${chosenTxt}</span>`+
      (r.ok?"":` · <span class="good">${acc.length>1?"נכונות":"הנכונה"}: ${correctTxt}</span>`)+
      (v.explanationHtml?`<br>${v.explanationHtml}`:"")+(v.official?"":" (לא רשמי)")+`</div></div>`;
  }).join("");
}

