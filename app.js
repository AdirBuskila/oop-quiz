/* MCQ exam trainer (course-agnostic; course data comes from questions.js meta) — vanilla JS, no modules, no runtime deps.
   Loads window.CC_QUIZ = {meta, contexts, questions} from questions.js (generated by
   tools/build_questions.py — never hand-edit it). Ported from databases-quiz:
   - math is PRE-RENDERED MathML inside the *Html fields (questionHtml, option .html,
     explanationHtml, context textHtml/captionHtml/titleHtml). Nothing renders math at runtime.
   - answers are stored by stable option id (correctId / acceptedIds); options are
     Fisher–Yates shuffled on every render unless q.lockOrder (an option cites siblings by letter).
   - duplicates across exams are kept (full-exam replay); dedupePool() de-dups topic/random pools. */

