/* ---------- theme toggle ---------- */
(function initTheme(){
  const btn = document.getElementById("themeToggle");
  if(!btn) return;
  const root = document.documentElement;
  const systemDark = () => !window.matchMedia || !window.matchMedia("(prefers-color-scheme: light)").matches;
  const effective = () => root.dataset.theme || (systemDark() ? "dark" : "light");
  const paint = () => { btn.textContent = effective()==="dark" ? "🌙" : "☀️"; };
  paint();
  btn.addEventListener("click", () => {
    const nxt = effective()==="dark" ? "light" : "dark";
    root.dataset.theme = nxt;
    try{ localStorage.setItem(THEME_KEY, nxt); }catch(e){}
    paint();
  });
  if(window.matchMedia){
    const mq=window.matchMedia("(prefers-color-scheme: light)");
    if(mq && mq.addEventListener) mq.addEventListener("change", () => { if(!root.dataset.theme) paint(); });
  }
})();

/* ---------- learning section ----------
   learn.js (generated by tools/build_learn.py from docs/briefs/*.md) provides
   window.LEARN = {chapters:[{id,title,topic,kind,html}], meta} (a bare array is also accepted).
   The entry button hides itself while there are no chapters. Clicks inside a brief are
   delegated: .qref peeks at a real exam question, .xref jumps to another chapter,
   .learn-drill starts a topic drill. Deep link: index.html?learn=<chapterId>. */
function learnChapters(){
  const L=window.LEARN;
  if(Array.isArray(L)) return L;
  return (L && Array.isArray(L.chapters)) ? L.chapters : [];
}
let openLearnAt = null;   // set by initLearn; used by the ?learn= deep link
(function initLearn(){
  const data = learnChapters();
  const entry = document.getElementById("learnEntry");
  const screen = document.getElementById("screen-learn");
  if(!entry || !screen) return;
  if(!data.length){ entry.style.display = "none"; return; }

  const toc=$("#learnToc"), content=$("#learnContent"), fill=$("#learnProgressFill"), pos=$("#learnPos");
  const prevB=$("#learnPrev"), nextB=$("#learnNext"), toggle=$("#learnTocToggle"), backdrop=$("#learnBackdrop");
  const backB=$("#learnBackBtn");
  let idx=0, built=false;

  function buildToc(){
    toc.innerHTML = data.map((s,i)=>
      `<button data-i="${i}"${s.kind==="cheat"?' class="cheat"':''}>${labelHtml(s.title)}</button>`).join("");
    toc.querySelectorAll("button").forEach(b=> b.onclick=()=>{ go(+b.dataset.i); closeDrawer(); });
    built=true;
  }
  function go(i){
    idx=Math.max(0,Math.min(data.length-1,i));
    const s=data[idx];
    // each brief is written to be read then drilled, so surface the drill entry point
    const n = s.topic ? countFor(s.topic,{officialOnly:false,mistakesOnly:false}) : 0;
    const drill = n ? `<button type="button" class="btn primary learn-drill" data-topic="${escapeHtml(s.topic)}">תרגל נושא זה ▶ <span class="n">${n}</span></button>` : "";
    const kind = s.kind==="cheat" ? `<span class="learn-kind">דף עזר</span>` : "";
    content.innerHTML = `<div class="learn-head"><h2 class="learn-h">${labelHtml(s.title)}${kind}</h2>${drill}</div>` + (s.html||"");
    content.dataset.chapter = s.id || "";
    toc.querySelectorAll("button").forEach((b,j)=> b.classList.toggle("active", j===idx));
    const active=toc.querySelector("button.active"); if(active) active.scrollIntoView({block:"nearest"});
    markScrollable();
    fill.style.width = ((idx+1)/data.length*100)+"%";
    pos.textContent = `${idx+1} / ${data.length}`;
    prevB.disabled=idx===0; nextB.disabled=idx===data.length-1;
    window.scrollTo({top:0,behavior:"smooth"}); content.focus({preventScroll:true});
  }
  /* Wide tables and display formulas scroll inside their own box. Flag the ones that
     actually overflow so CSS shows an edge shadow — a clipped formula with no hint reads as
     broken. Recomputed on resize (rotating a phone changes which ones overflow). */
  function markScrollable(){
    content.querySelectorAll(".math-block,.tbl-wrap").forEach(el=>
      el.classList.toggle("scrollable", el.scrollWidth > el.clientWidth + 1));
  }
  let rzT;
  window.addEventListener("resize", ()=>{
    clearTimeout(rzT);
    rzT=setTimeout(()=>{ if(!screen.classList.contains("hidden")) markScrollable(); }, 150);
  });
  function openLearn(){ if(!built) buildToc(); show("screen-learn"); go(idx); }
  function setDrawer(open){ toc.classList.toggle("open",open); backdrop.classList.toggle("hidden",!open); toggle.setAttribute("aria-expanded", open?"true":"false"); }
  function closeDrawer(){ setDrawer(false); }
  openLearnAt = id=>{
    const j=data.findIndex(c=>c.id===id);
    if(j<0) return false;
    idx=j; openLearn(); return true;
  };

  entry.onclick=openLearn;
  backB.onclick=()=>{ closeDrawer(); closePeek(); quit(); };
  prevB.onclick=()=>go(idx-1);
  nextB.onclick=()=>go(idx+1);
  toggle.onclick=()=>setDrawer(!toc.classList.contains("open"));
  backdrop.onclick=closeDrawer;

  /* ----- question peek: click a `26B-B-Q3` reference inside a brief ----- */
  const peek=$("#qpeek"), peekBody=$("#qpeekBody"), peekDrill=$("#qpeekDrill");
  let peekTopic=null;
  function openPeek(id){
    const q=QS.find(x=>x.id===id);
    if(!q || !peek) return;
    $("#qpeekId").textContent = q.id;
    $("#qpeekSource").textContent = examLabelOf(q) + (Number.isInteger(q.num) ? ` · שאלה ${q.num}` : "");
    const badge=$("#qpeekBadge");
    badge.textContent = q.official ? "מפתרון רשמי" : "תשובה לא רשמית";
    badge.className = "chip " + (q.official?"official":"unofficial");
    // source order with the accepted answer(s) marked: the brief discusses this exact
    // question, so shuffling here would only make it harder to follow.
    peekBody.innerHTML =
      (q.contextId ? contextHtml(CTX[q.contextId]) : "") +
      `<div class="qpeek-q">${questionHtml(q)}</div>` + extrasHtml(q) +
      `<ol class="qpeek-opts">` + (q.options||[]).map((o,i)=>
        `<li class="${isAccepted(q,o.id)?"right":""}" data-oid="${escapeHtml(o.id)}"><span class="key">${HE_KEYS[i]||i+1}</span>`+
        `<span class="txt">${optionHtml(o)}</span></li>`).join("") + `</ol>` +
      (q.explanationHtml ? `<div class="qpeek-exp"><strong>הסבר:</strong> ${q.explanationHtml}</div>` : "");
    peekTopic=q.topic;
    peekDrill.classList.toggle("hidden", !countFor(q.topic,{officialOnly:false,mistakesOnly:false}));
    peek.classList.remove("hidden");
    peekBody.scrollTop=0;
    $("#qpeekClose").focus({preventScroll:true});
  }
  function closePeek(){ if(!peek) return; peek.classList.add("hidden"); peekBody.innerHTML=""; peekTopic=null; }
  const peekOpen=()=> peek && !peek.classList.contains("hidden");
  if(peek){
    peek.addEventListener("click", e=>{ if(e.target===peek) closePeek(); });
    $("#qpeekClose").onclick=closePeek;
    peekDrill.onclick=()=>{ const t=peekTopic; closePeek(); closeDrawer(); startTopicPractice(t); };
  }

  content.addEventListener("click", e=>{
    const qref=e.target.closest(".qref");
    if(qref){ openPeek(qref.dataset.q); return; }
    const xref=e.target.closest(".xref");
    if(xref){
      e.preventDefault();
      const j=data.findIndex(c=>c.id===xref.dataset.chapter);
      if(j>=0) go(j);
      return;
    }
    const drill=e.target.closest(".learn-drill");
    if(drill){ closeDrawer(); startTopicPractice(drill.dataset.topic); }
  });
  document.addEventListener("keydown", e=>{
    const lb=$("#lightbox");
    if(lb && !lb.classList.contains("hidden")) return;       // bindGlobal closes the lightbox
    // the peek sits above the brief: Escape closes it, chapter nav stays put
    if(peekOpen()){ if(e.key==="Escape") closePeek(); return; }
    if(screen.classList.contains("hidden")) return;
    if(e.key==="ArrowLeft") go(idx+1);
    else if(e.key==="ArrowRight") go(idx-1);
    else if(e.key==="Escape"){ closeDrawer(); quit(); }
  });
})();

/* ---------- single entry point into a topic drill ---------- */
function startTopicPractice(topic){
  if(!TOPICS.some(([k])=>k===topic)) return false;
  if(countFor(topic,{officialOnly:false,mistakesOnly:false})===0) return false;
  S.mode="practice"; S.topic=topic;
  const r=document.querySelector('input[name=mode][value="practice"]'); if(r) r.checked=true;
  $("#examOpts").classList.add("hidden");
  $("#officialOnly").checked=false; $("#mistakesOnly").checked=false;
  initStart();
  startSession();
  return true;
}
/* deep links: index.html?practice=<topicKey>  |  index.html?learn=<chapterId> */
function autoStartFromURL(){
  let t, c;
  try{ const u=new URLSearchParams(location.search); t=u.get("practice"); c=u.get("learn"); }catch(e){ return; }
  if(t) startTopicPractice(t);
  else if(c && openLearnAt) openLearnAt(c);
}

