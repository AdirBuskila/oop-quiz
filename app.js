/* Label -> HTML. "≤m" / "≤p" are bidi-neutral+Latin; unisolated in an RTL line they render
   mirrored and reordered as "(m≥)". Isolate them LTR. */
function labelHtml(l){ return escapeHtml(l).replace(/≤[mp]/g, m=>`<bdi dir="ltr">${m}</bdi>`); }
function topicLabelOf(q){ return TOPIC_LABEL[q.topic] || q.topicLabel || q.topic; }

