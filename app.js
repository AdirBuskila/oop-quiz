function selectedExam(){ const el=$("#examPick"); return (S.mode==="exam" && el) ? el.value : ""; }
function examQuestions(code){ return QS.filter(q=>q.examCode===code); }
function qNum(q){ if(Number.isInteger(q.num)) return q.num; const m=String(q.id).match(/-Q(\d+)$/); return m?parseInt(m[1],10):0; }
function examLabelOf(q){ return q.examLabel || q.examCode || ""; }
/* Exam-picker order: sample papers first (no place in the chronology), then real exams
   oldest→newest, newest at the bottom — same rule as the sibling apps. */
function examOrder(code){
  const c=String(code);
  if(/^SAMP/.test(c)) return [0, 0, c];
  const m=c.match(/^(\d{2})/);
  return [1, m?2000+parseInt(m[1],10):9999, c];
}
function byExamOrder(a,b){ const x=examOrder(a), y=examOrder(b); return (x[0]-y[0]) || (x[1]-y[1]) || String(x[2]).localeCompare(String(y[2])); }
function populateExamPick(){
  const sel=$("#examPick"); if(!sel) return;
  const seen=new Map();
  QS.forEach(q=>{ if(q.examCode && !seen.has(q.examCode)) seen.set(q.examCode, examLabelOf(q)); });
  const keep=sel.value;
  sel.innerHTML = `<option value="">אקראי (כל המאגר)</option>` +
    [...seen.entries()].sort((a,b)=>byExamOrder(a[0],b[0]))
      .map(([code,label])=>`<option value="${escapeHtml(code)}">${escapeHtml(label)} (${examQuestions(code).length})</option>`).join("");
  if(keep && seen.has(keep)) sel.value=keep;
  sel.onchange=()=>{ syncExamOpts(); updatePoolInfo(); };
}
