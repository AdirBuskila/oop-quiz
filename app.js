/* Brand accent from course.config.json (via META). The stylesheet keeps a neutral default and
   derives glow/grad/ring from --brand/--brand2; --brand-ink is picked for contrast here. */
(function applyBrand(){
  const hex = c => /^#[0-9a-f]{6}$/i.test(c||"") ? c : null;
  const b1 = hex(META.accent), b2 = hex(META.accent2) || b1;
  if(!b1) return;
  const st = document.documentElement.style;
  st.setProperty("--brand", b1); st.setProperty("--brand2", b2);
  const lum = [1,3,5].map(i=>{ const v=parseInt(b1.substr(i,2),16)/255; return v<=.03928 ? v/12.92 : Math.pow((v+.055)/1.055,2.4); });
  const L = .2126*lum[0] + .7152*lum[1] + .0722*lum[2];
  st.setProperty("--brand-ink", L > .35 ? "#0b0b1a" : "#ffffff");
})();

