/* ---------- helpers ---------- */
const $ = s => document.querySelector(s);
function shuffle(a){ a=a.slice(); for(let i=a.length-1;i>0;i--){ const j=Math.floor(Math.random()*(i+1)); [a[i],a[j]]=[a[j],a[i]]; } return a; }
function show(id){ document.querySelectorAll(".screen").forEach(s=>s.classList.add("hidden")); $("#"+id).classList.remove("hidden"); window.scrollTo({top:0,behavior:"smooth"}); }
function escapeHtml(s){ return String(s).replace(/[&<>"]/g,m=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;"}[m])); }
function optById(q,id){ return (q.options||[]).find(o=>o.id===id); }
function hasHebrew(s){ return /[֐-׿]/.test(String(s)); }
/* accepted answers: usually just [correctId]; some questions accept more than one
   (appeal / ambiguous key). Grade "chosen ∈ accepted". */
function acceptedIdsOf(q){ return (Array.isArray(q.acceptedIds) && q.acceptedIds.length) ? q.acceptedIds : [q.correctId]; }
function isAccepted(q,id){ return id!=null && acceptedIdsOf(q).includes(id); }

/* Duplicates are kept in the bank (a whole past paper must replay in full); topic/random
   practice pools show each distinct question once. */
function dedupePool(arr){
  const seen=new Set(), out=[];
  for(const q of arr){ const k=q.dedupKey||q.id; if(seen.has(k)) continue; seen.add(k); out.push(q); }
  return out;
}
function filterMatch(q, topic, opts){
  if(topic!=="all" && q.topic!==topic) return false;
  if(opts.officialOnly && !q.official) return false;
  if(opts.mistakesOnly){ const r=P.perQ[q.id]; if(!r || r.correct) return false; }
  return true;
}
function filteredPool(topic, opts){ return dedupePool(QS.filter(q=>filterMatch(q, topic, opts))); }
function countFor(topic, opts){ return filteredPool(topic, opts).length; }

/* ---------- rendering pieces (all *Html fields are trusted build output) ---------- */
function contextHtml(ctx){
  if(!ctx) return "";
  let h = `<div class="ctx ctx-${escapeHtml(ctx.kind||"text")}">`;
  if(ctx.title) h += `<div class="ctx-title">${ctx.titleHtml || escapeHtml(ctx.title)}</div>`;
  if(ctx.image) h += `<figure class="ctx-fig"><img class="q-img ctx-img" src="${escapeHtml(ctx.image)}" alt="${escapeHtml(ctx.caption||ctx.title||"")}" loading="lazy">`+
                     (ctx.caption?`<figcaption>${ctx.captionHtml || escapeHtml(ctx.caption)}</figcaption>`:"")+`</figure>`;
  if(ctx.text) h += `<div class="ctx-text">${ctx.textHtml || escapeHtml(ctx.text)}</div>`;
  h += `</div>`;
  return h;
}
function extrasHtml(q){
  return q.image ? `<figure class="q-fig"><img class="q-img" src="${escapeHtml(q.image)}" alt="" loading="lazy"></figure>` : "";
}
function questionHtml(q){ return q.questionHtml || escapeHtml(q.question||""); }
function optionHtml(o){
  if(!o) return "";
  const type = o.type || "text";
  if(type==="image") return `<img class="opt-img" src="${escapeHtml(o.value)}" alt="" loading="lazy">`;
  const body = o.html || escapeHtml(o.value);
  if(type==="math") return body;                                   // already an LTR .opt-math span
  if(!hasHebrew(o.value)) return `<span class="opt-ltr" dir="ltr">${body}</span>`;
  return body;
}

